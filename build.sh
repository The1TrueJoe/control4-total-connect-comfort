#!/usr/bin/env bash
# Concatenates driver/src/ into driver/driver.lua, then packages
# total_connect_comfort.c4z (landed at the repo root) using
# snap-one/drivers-driverpackager (dp3).
# Requires: Python 3, lxml (`pip3 install lxml`), luac, git
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

DRIVER_DIR="driver"
DP3="tools/driverpackager/dp3/driverpackager.py"

if [[ ! -f "$DP3" ]]; then
  echo "Cloning snap-one/drivers-driverpackager into tools/driverpackager..."
  mkdir -p tools
  git clone --depth=1 https://github.com/snap-one/drivers-driverpackager tools/driverpackager
fi

# ---------------------------------------------------------------------------
# Step 1: Concatenate source files into driver/driver.lua
# ---------------------------------------------------------------------------

echo "Concatenating driver/src/ -> driver/driver.lua..."
{
  echo '-- Total Connect Comfort Thermostat Driver'
  echo '-- AUTO-GENERATED by build.sh — edit files in driver/src/ instead.'
  echo '---@diagnostic disable: undefined-global'
  for f in "$DRIVER_DIR"/src/*.lua; do
    echo
    cat "$f"
  done
} > "$DRIVER_DIR/driver.lua"
echo "  OK  driver/driver.lua ($(wc -l < "$DRIVER_DIR/driver.lua") lines)"
echo

echo "Validating Lua..."
luac -p "$DRIVER_DIR/driver.lua"
echo "  OK  driver/driver.lua"
echo

# ---------------------------------------------------------------------------
# Step 2: Stamp driver.xml with build date and version
# ---------------------------------------------------------------------------

echo "Stamping driver.xml..."
BUILD_DATE=$(date +"%m/%d/%Y %H:%M")
VERSION=$(git rev-list --count HEAD 2>/dev/null || echo "1")
sed -i '' "s|<modified>.*</modified>|<modified>${BUILD_DATE}</modified>|" "$DRIVER_DIR/driver.xml"
sed -i '' "s|<version>[^<]*</version>|<version>${VERSION}</version>|" "$DRIVER_DIR/driver.xml"
echo "  version=${VERSION}  modified=${BUILD_DATE}"
echo

# ---------------------------------------------------------------------------
# Step 3: Package with snap-one driverpackager (dp3)
# ---------------------------------------------------------------------------

echo "Running driverpackager..."
python3 "$DP3" -v "$DRIVER_DIR" . total_connect_comfort.c4zproj

C4Z="total_connect_comfort.c4z"
echo
echo "Built: $C4Z ($(wc -c < "$C4Z" | tr -d ' ') bytes)"
